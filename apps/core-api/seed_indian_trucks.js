async function seed() {
  console.log('Seeding 11 authentic Indian Container Trucks into VehicleType table...');
  const vehicleTypeModel = prisma.vehicleType || prisma.vehicle_types;
  for (const t of TRUCKS) {
    await vehicleTypeModel.upsert({
      where: { id: t.id },
      update: {
        name: t.name,
        make: t.make,
        model: t.model,
        category: t.category,
        bodyType: t.bodyType,
        fuelType: 'DIESEL',
        emissionStandard: 'BS-VI',
        internalLength: t.internalLength.toString(),
        internalWidth: t.internalWidth.toString(),
        internalHeight: t.internalHeight.toString(),
        dimensionUnit: 'CM',
        maxPayload: t.maxPayload.toString(),
        weightUnit: 'KG',
        volumetricCapacity: t.volumetricCapacity.toString(),
        volumeUnit: 'M3',
        verificationStatus: 'VERIFIED',
        isActive: true,
        updatedAt: new Date(),
      },
      create: {
        id: t.id,
        name: t.name,
        make: t.make,
        model: t.model,
        category: t.category,
        bodyType: t.bodyType,
        fuelType: 'DIESEL',
        emissionStandard: 'BS-VI',
        internalLength: t.internalLength.toString(),
        internalWidth: t.internalWidth.toString(),
        internalHeight: t.internalHeight.toString(),
        dimensionUnit: 'CM',
        maxPayload: t.maxPayload.toString(),
        weightUnit: 'KG',
        volumetricCapacity: t.volumetricCapacity.toString(),
        volumeUnit: 'M3',
        verificationStatus: 'VERIFIED',
        isActive: true,
        updatedAt: new Date(),
      },
    });
    console.log(`✓ Upserted ${t.id}: ${t.name}`);
  }
  console.log('Seeding completed successfully!');
}

seed().finally(() => prisma.$disconnect());
