import {
  CargoItemInput,
  PhysicalCargoInstance,
  Placement,
  Point3D,
  TruckCargoSpace,
} from './types';

/**
 * Expands high-level CargoItemInput array into individual physical package instances.
 * Validates strictly against zero or negative dimensions and weights.
 */
export function expandAndValidateCargo(
  items: CargoItemInput[],
): { instances: PhysicalCargoInstance[]; errors: string[] } {
  const instances: PhysicalCargoInstance[] = [];
  const errors: string[] = [];

  for (const item of items) {
    if (!item.cargoId || typeof item.cargoId !== 'string') {
      errors.push(`Cargo item missing valid cargoId: ${JSON.stringify(item)}`);
      continue;
    }

    if (!Number.isInteger(item.lengthMm) || item.lengthMm <= 0) {
      errors.push(`Cargo ${item.cargoId} has invalid lengthMm: ${item.lengthMm}. Must be positive integer.`);
    }
    if (!Number.isInteger(item.widthMm) || item.widthMm <= 0) {
      errors.push(`Cargo ${item.cargoId} has invalid widthMm: ${item.widthMm}. Must be positive integer.`);
    }
    if (!Number.isInteger(item.heightMm) || item.heightMm <= 0) {
      errors.push(`Cargo ${item.cargoId} has invalid heightMm: ${item.heightMm}. Must be positive integer.`);
    }
    if (!Number.isInteger(item.weightGrams) || item.weightGrams <= 0) {
      errors.push(`Cargo ${item.cargoId} has invalid weightGrams: ${item.weightGrams}. Must be positive integer.`);
    }
    if (!Number.isInteger(item.quantity) || item.quantity < 0) {
      errors.push(`Cargo ${item.cargoId} has invalid quantity: ${item.quantity}. Must be non-negative integer.`);
    }

    if (errors.length > 0) {
      continue;
    }

    const volume = item.lengthMm * item.widthMm * item.heightMm;

    for (let i = 1; i <= item.quantity; i++) {
      instances.push({
        instanceId: `${item.cargoId}#${i}`,
        cargoId: item.cargoId,
        description: item.description,
        lengthMm: item.lengthMm,
        widthMm: item.widthMm,
        heightMm: item.heightMm,
        weightGrams: item.weightGrams,
        volumeMm3: volume,

        isStackable: item.isStackable ?? true,
        maxStackWeightGrams: item.maxStackWeightGrams,
        maxStackTiers: item.maxStackTiers,
        isFragile: item.isFragile ?? false,

        allowRotationHorizontal: item.allowRotationHorizontal ?? true,
        allowRotationVertical: item.allowRotationVertical ?? false,
        allowedOrientations: item.allowedOrientations,

        loadingPriority: item.loadingPriority ?? 1,
        unloadingSequence: item.unloadingSequence ?? 1,
      });
    }
  }

  return { instances, errors };
}

/**
 * Sorts physical cargo instances in a strictly deterministic constructive order:
 * 1. Loading Priority (descending: higher priority loaded earlier)
 * 2. Unloading Sequence (descending: items for later delivery stops loaded deeper/earlier)
 * 3. Volume (descending: largest items first — Best-Fit Decreasing)
 * 4. Weight (descending: heavier items placed lower/earlier)
 * 5. Instance ID (ascending: guaranteed deterministic tie-breaking)
 */
export function sortCargoInstances(instances: PhysicalCargoInstance[]): PhysicalCargoInstance[] {
  return [...instances].sort((a, b) => {
    // 1. Loading priority descending
    if (a.loadingPriority !== b.loadingPriority) {
      return b.loadingPriority - a.loadingPriority;
    }
    // 2. Unloading sequence descending (LIFO: later stops loaded deeper)
    if (a.unloadingSequence !== b.unloadingSequence) {
      return b.unloadingSequence - a.unloadingSequence;
    }
    // 3. Volume descending
    if (a.volumeMm3 !== b.volumeMm3) {
      return b.volumeMm3 - a.volumeMm3;
    }
    // 4. Weight descending
    if (a.weightGrams !== b.weightGrams) {
      return b.weightGrams - a.weightGrams;
    }
    // 5. Deterministic tie-breaker
    return a.instanceId.localeCompare(b.instanceId);
  });
}

/**
 * Checks if a point is strictly enclosed inside any existing placed box.
 */
function isPointInsidePlacement(point: Point3D, p: Placement): boolean {
  return (
    point.xMm >= p.xMm &&
    point.xMm < p.xMm + p.lengthMm &&
    point.yMm >= p.yMm &&
    point.yMm < p.yMm + p.widthMm &&
    point.zMm >= p.zMm &&
    point.zMm < p.zMm + p.heightMm
  );
}

/**
 * Generates and updates candidate anchor placement corners based on placed boxes.
 */
export function generateCandidatePoints(
  currentPoints: Point3D[],
  newPlacement: Placement,
  truck: TruckCargoSpace,
  allPlacements: Placement[],
): Point3D[] {
  // New extreme/anchor points generated by the newly placed box
  const newCorners: Point3D[] = [
    { xMm: newPlacement.xMm + newPlacement.lengthMm, yMm: newPlacement.yMm, zMm: newPlacement.zMm },
    { xMm: newPlacement.xMm, yMm: newPlacement.yMm + newPlacement.widthMm, zMm: newPlacement.zMm },
    { xMm: newPlacement.xMm, yMm: newPlacement.yMm, zMm: newPlacement.zMm + newPlacement.heightMm },
  ];

  const pool = [...currentPoints, ...newCorners];
  const validPoints: Point3D[] = [];
  const seenKeys = new Set<string>();

  for (const pt of pool) {
    // 1. Must be within vehicle bounds
    if (pt.xMm < 0 || pt.xMm >= truck.lengthMm) continue;
    if (pt.yMm < 0 || pt.yMm >= truck.widthMm) continue;
    if (pt.zMm < 0 || pt.zMm >= truck.heightMm) continue;

    // 2. Must not be inside any placed box
    let inside = false;
    for (const p of allPlacements) {
      if (isPointInsidePlacement(pt, p)) {
        inside = true;
        break;
      }
    }
    if (inside) continue;

    // 3. Deduplicate
    const key = `${pt.xMm},${pt.yMm},${pt.zMm}`;
    if (!seenKeys.has(key)) {
      seenKeys.add(key);
      validPoints.push(pt);
    }
  }

  // Deterministic sorting: Z ascending (lowest first), then X ascending (front first), then Y ascending (left first)
  validPoints.sort((a, b) => {
    if (a.zMm !== b.zMm) return a.zMm - b.zMm;
    if (a.xMm !== b.xMm) return a.xMm - b.xMm;
    return a.yMm - b.yMm;
  });

  return validPoints;
}

/**
 * Calculates a deterministic placement fitness score.
 * Lower score = better, more compact placement (prefers bottom-front-left).
 */
export function scorePlacement(point: Point3D, dxMm: number, dyMm: number, dzMm: number): bigint {
  // BigInt arithmetic guarantees zero 64-bit integer overflow issues
  const zScore = BigInt(point.zMm) * 1_000_000_000_000n;
  const xScore = BigInt(point.xMm) * 1_000_000n;
  const yScore = BigInt(point.yMm) * 1_000n;
  const compactScore = BigInt(dxMm + dyMm + dzMm);

  return zScore + xScore + yScore + compactScore;
}
